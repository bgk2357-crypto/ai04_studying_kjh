BEGIN;

-- 기존 안내대로 생성한 테이블과 같은 구조입니다.
CREATE TABLE IF NOT EXISTS public.entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 20),
    message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 500),
    created_at TEXT NOT NULL
);

ALTER TABLE public.entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.entries FROM anon, authenticated;
GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT ON TABLE public.entries TO service_role;

-- 개수 확인과 저장을 하나의 트랜잭션에서 처리합니다.
CREATE OR REPLACE FUNCTION public.guestbook_add_entry(p_name TEXT, p_message TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF p_name IS NULL OR p_message IS NULL
       OR char_length(btrim(p_name)) NOT BETWEEN 1 AND 20
       OR char_length(btrim(p_message)) NOT BETWEEN 1 AND 500 THEN
        RAISE EXCEPTION 'Invalid guestbook input' USING ERRCODE = '22023';
    END IF;

    LOCK TABLE public.entries IN SHARE ROW EXCLUSIVE MODE;
    IF (SELECT count(*) FROM public.entries) >= 1000 THEN
        RETURN FALSE;
    END IF;

    INSERT INTO public.entries (name, message, created_at)
    VALUES (
        btrim(p_name), btrim(p_message),
        to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI "KST"')
    );
    RETURN TRUE;
END;
$$;

REVOKE ALL ON FUNCTION public.guestbook_add_entry(TEXT, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.guestbook_add_entry(TEXT, TEXT) TO service_role;

COMMIT;
NOTIFY pgrst, 'reload schema';
